import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import { computeStats } from './stats';
import { Reading } from './storage';

// Builds a one-page summary of the readings as a PDF and opens the share sheet.
export async function exportPdf(readings: Reading[]) {
  const s = computeStats(readings);
  if (!s) return;

  const first = new Date(readings[0].time).toLocaleDateString();
  const last = new Date(readings[readings.length - 1].time).toLocaleDateString();

  // Only the latest 60 readings so everything fits on one page
  const rows = readings
    .slice(-60)
    .reverse()
    .map(
      r =>
        `<tr><td>${new Date(r.time).toLocaleString()}</td><td>${r.value}</td><td>${r.tag}</td></tr>`
    )
    .join('');

  const html = `
  <html>
    <body style="font-family: Arial, sans-serif; padding: 24px; color: #111;">
      <h1 style="margin-bottom: 4px;">Glucose Summary</h1>
      <p style="margin-top: 0; color: #555;">${first} to ${last} &middot; ${s.count} readings</p>

      <table style="width:100%; border-collapse: collapse; margin: 16px 0;">
        <tr>
          <td style="padding:8px; border:1px solid #999;"><b>Average</b><br>${s.avg} mg/dL</td>
          <td style="padding:8px; border:1px solid #999;"><b>Lowest</b><br>${s.min} mg/dL</td>
          <td style="padding:8px; border:1px solid #999;"><b>Highest</b><br>${s.max} mg/dL</td>
        </tr>
        <tr>
          <td style="padding:8px; border:1px solid #999;"><b>In range (70-180)</b><br>${s.pctInRange}%</td>
          <td style="padding:8px; border:1px solid #999;"><b>Low (under 70)</b><br>${s.pctLow}%</td>
          <td style="padding:8px; border:1px solid #999;"><b>High (over 180)</b><br>${s.pctHigh}%</td>
        </tr>
      </table>

      <h3>Recent readings</h3>
      <table style="width:100%; border-collapse: collapse; font-size: 12px;">
        <tr style="background:#eee;">
          <th style="text-align:left; padding:4px; border:1px solid #999;">Time</th>
          <th style="text-align:left; padding:4px; border:1px solid #999;">mg/dL</th>
          <th style="text-align:left; padding:4px; border:1px solid #999;">Context</th>
        </tr>
        ${rows}
      </table>

      <p style="color:#666; font-size:11px; margin-top:16px;">
        Generated by GlucoseBridge. This is a logging tool, not medical advice.
        Readings were confirmed by the user. Always follow your doctor's guidance.
      </p>
    </body>
  </html>`;

  const { uri } = await Print.printToFileAsync({ html });
  await Sharing.shareAsync(uri, { mimeType: 'application/pdf', UTI: 'com.adobe.pdf' });
}